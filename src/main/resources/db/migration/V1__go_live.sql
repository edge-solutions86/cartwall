-- The schema the house went live on.
--
-- Everything the traffic department needs on day one: signals and their clocks,
-- accounts and their conflict codes, the rate cards, orders and lines, the logs and
-- what was bumped off them, and the counters the document numbers come from.
--
-- Written by hand. Every constraint is named, as a function of its columns, so a
-- later migration that drops one can name it. Tables are created in the one order
-- the foreign keys allow.

CREATE TABLE station (
    call            VARCHAR(16)   NOT NULL,
    band            VARCHAR(32)   NOT NULL,
    frequency       NUMERIC(6, 1) NOT NULL,
    city_of_license VARCHAR(120)  NOT NULL,
    service         VARCHAR(32)   NOT NULL,
    market          VARCHAR(120)  NOT NULL,
    daytimer        BOOLEAN       NOT NULL,
    carries         VARCHAR(16),
    commercial_load INTEGER       NOT NULL,
    CONSTRAINT pk_station PRIMARY KEY (call),
    CONSTRAINT fk_station_carries_station FOREIGN KEY (carries) REFERENCES station (call)
);

CREATE TABLE daypart (
    id         INTEGER GENERATED BY DEFAULT AS IDENTITY,
    station    VARCHAR(16)  NOT NULL,
    code       VARCHAR(16)  NOT NULL,
    name       VARCHAR(120) NOT NULL,
    days       VARCHAR(32)  NOT NULL,
    first_hour INTEGER      NOT NULL,
    last_hour  INTEGER      NOT NULL,
    CONSTRAINT pk_daypart PRIMARY KEY (id),
    CONSTRAINT uq_daypart_station_code UNIQUE (station, code),
    CONSTRAINT fk_daypart_station_station FOREIGN KEY (station) REFERENCES station (call)
);

CREATE TABLE clock (
    id        INTEGER GENERATED BY DEFAULT AS IDENTITY,
    station   VARCHAR(16)  NOT NULL,
    code      VARCHAR(16)  NOT NULL,
    name      VARCHAR(120) NOT NULL,
    effective DATE         NOT NULL,
    CONSTRAINT pk_clock PRIMARY KEY (id),
    CONSTRAINT uq_clock_station_code_effective UNIQUE (station, code, effective),
    CONSTRAINT fk_clock_station_station FOREIGN KEY (station) REFERENCES station (call)
);

CREATE TABLE clock_break (
    id       INTEGER GENERATED BY DEFAULT AS IDENTITY,
    clock_id INTEGER     NOT NULL,
    number   INTEGER     NOT NULL,
    kind     VARCHAR(32) NOT NULL,
    position INTEGER     NOT NULL,
    length   INTEGER     NOT NULL,
    units    INTEGER     NOT NULL,
    paid     BOOLEAN     NOT NULL,
    CONSTRAINT pk_clock_break PRIMARY KEY (id),
    CONSTRAINT uq_clock_break_clock_id_number UNIQUE (clock_id, number),
    CONSTRAINT fk_clock_break_clock_id_clock FOREIGN KEY (clock_id) REFERENCES clock (id) ON DELETE CASCADE
);

CREATE TABLE clock_assignment (
    id         INTEGER GENERATED BY DEFAULT AS IDENTITY,
    station    VARCHAR(16)  NOT NULL,
    effective  DATE         NOT NULL,
    ordinal    INTEGER      NOT NULL,
    label      VARCHAR(120) NOT NULL,
    days       VARCHAR(32)  NOT NULL,
    first_hour INTEGER      NOT NULL,
    last_hour  INTEGER      NOT NULL,
    clock_code VARCHAR(16)  NOT NULL,
    source     VARCHAR(32)  NOT NULL,
    CONSTRAINT pk_clock_assignment PRIMARY KEY (id),
    CONSTRAINT uq_clock_assignment_station_effective_ordinal UNIQUE (station, effective, ordinal),
    CONSTRAINT fk_clock_assignment_station_station FOREIGN KEY (station) REFERENCES station (call)
);

CREATE TABLE agency (
    code              VARCHAR(16)   NOT NULL,
    name              VARCHAR(120)  NOT NULL,
    rate              NUMERIC(5, 4) NOT NULL,
    advertiser_liable BOOLEAN       NOT NULL,
    CONSTRAINT pk_agency PRIMARY KEY (code)
);

CREATE TABLE advertiser (
    code   VARCHAR(16)  NOT NULL,
    name   VARCHAR(120) NOT NULL,
    agency VARCHAR(16),
    parent VARCHAR(16),
    credit VARCHAR(32)  NOT NULL,
    CONSTRAINT pk_advertiser PRIMARY KEY (code),
    CONSTRAINT fk_advertiser_agency_agency FOREIGN KEY (agency) REFERENCES agency (code),
    CONSTRAINT fk_advertiser_parent_advertiser FOREIGN KEY (parent) REFERENCES advertiser (code)
);

CREATE TABLE advertiser_category (
    id         INTEGER GENERATED BY DEFAULT AS IDENTITY,
    advertiser VARCHAR(16) NOT NULL,
    path       VARCHAR(64) NOT NULL,
    root       VARCHAR(32) NOT NULL,
    CONSTRAINT pk_advertiser_category PRIMARY KEY (id),
    CONSTRAINT uq_advertiser_category_advertiser_path UNIQUE (advertiser, path),
    CONSTRAINT fk_advertiser_category_advertiser_advertiser
        FOREIGN KEY (advertiser) REFERENCES advertiser (code) ON DELETE CASCADE
);

CREATE INDEX ix_advertiser_category_root ON advertiser_category (root);

CREATE TABLE cut (
    cart       VARCHAR(16) NOT NULL,
    isci       VARCHAR(24) NOT NULL,
    advertiser VARCHAR(16) NOT NULL,
    length     INTEGER     NOT NULL,
    actual     INTEGER     NOT NULL,
    first_air  DATE        NOT NULL,
    last_air   DATE,
    killed     BOOLEAN     NOT NULL,
    CONSTRAINT pk_cut PRIMARY KEY (cart),
    CONSTRAINT fk_cut_advertiser_advertiser FOREIGN KEY (advertiser) REFERENCES advertiser (code) ON DELETE CASCADE
);

CREATE TABLE rate_card (
    id        INTEGER GENERATED BY DEFAULT AS IDENTITY,
    code      VARCHAR(16) NOT NULL,
    station   VARCHAR(16) NOT NULL,
    effective DATE        NOT NULL,
    CONSTRAINT pk_rate_card PRIMARY KEY (id),
    CONSTRAINT uq_rate_card_station_effective UNIQUE (station, effective),
    CONSTRAINT fk_rate_card_station_station FOREIGN KEY (station) REFERENCES station (call)
);

CREATE TABLE rate_quote (
    id      INTEGER GENERATED BY DEFAULT AS IDENTITY,
    card_id INTEGER     NOT NULL,
    daypart VARCHAR(16) NOT NULL,
    grade   VARCHAR(32) NOT NULL,
    thirty  INTEGER     NOT NULL,
    CONSTRAINT pk_rate_quote PRIMARY KEY (id),
    CONSTRAINT uq_rate_quote_card_id_daypart_grade UNIQUE (card_id, daypart, grade),
    CONSTRAINT fk_rate_quote_card_id_rate_card FOREIGN KEY (card_id) REFERENCES rate_card (id) ON DELETE CASCADE
);

CREATE TABLE sales_order (
    number      VARCHAR(24)  NOT NULL,
    advertiser  VARCHAR(16)  NOT NULL,
    agency      VARCHAR(16),
    written     DATE         NOT NULL,
    salesperson VARCHAR(16)  NOT NULL,
    campaign    VARCHAR(120) NOT NULL,
    status      VARCHAR(32)  NOT NULL,
    CONSTRAINT pk_sales_order PRIMARY KEY (number),
    CONSTRAINT fk_sales_order_advertiser_advertiser FOREIGN KEY (advertiser) REFERENCES advertiser (code),
    CONSTRAINT fk_sales_order_agency_agency FOREIGN KEY (agency) REFERENCES agency (code)
);

CREATE TABLE sales_line (
    id           INTEGER GENERATED BY DEFAULT AS IDENTITY,
    order_number VARCHAR(24) NOT NULL,
    number       INTEGER     NOT NULL,
    station      VARCHAR(16) NOT NULL,
    daypart      VARCHAR(16) NOT NULL,
    grade        VARCHAR(32) NOT NULL,
    length       INTEGER     NOT NULL,
    rate         INTEGER     NOT NULL,
    card_code    VARCHAR(16) NOT NULL,
    first_air    DATE        NOT NULL,
    last_air     DATE        NOT NULL,
    days         VARCHAR(32) NOT NULL,
    per_week     INTEGER     NOT NULL,
    CONSTRAINT pk_sales_line PRIMARY KEY (id),
    CONSTRAINT uq_sales_line_order_number_number UNIQUE (order_number, number),
    CONSTRAINT fk_sales_line_order_number_sales_order
        FOREIGN KEY (order_number) REFERENCES sales_order (number) ON DELETE CASCADE,
    CONSTRAINT fk_sales_line_station_station FOREIGN KEY (station) REFERENCES station (call)
);

CREATE TABLE line_rotation (
    id       INTEGER GENERATED BY DEFAULT AS IDENTITY,
    line_id  INTEGER     NOT NULL,
    position INTEGER     NOT NULL,
    cart     VARCHAR(16) NOT NULL,
    weight   INTEGER     NOT NULL,
    kind     VARCHAR(32) NOT NULL,
    CONSTRAINT pk_line_rotation PRIMARY KEY (id),
    CONSTRAINT uq_line_rotation_line_id_cart UNIQUE (line_id, cart),
    CONSTRAINT fk_line_rotation_line_id_sales_line FOREIGN KEY (line_id) REFERENCES sales_line (id) ON DELETE CASCADE,
    CONSTRAINT fk_line_rotation_cart_cut FOREIGN KEY (cart) REFERENCES cut (cart)
);

CREATE TABLE air_log (
    id          INTEGER GENERATED BY DEFAULT AS IDENTITY,
    station     VARCHAR(16)  NOT NULL,
    day         DATE         NOT NULL,
    state       VARCHAR(32)  NOT NULL,
    revision    INTEGER      NOT NULL,
    approved_by VARCHAR(120) NOT NULL,
    approved_at TIMESTAMP(6),
    released_at TIMESTAMP(6),
    CONSTRAINT pk_air_log PRIMARY KEY (id),
    CONSTRAINT uq_air_log_station_day UNIQUE (station, day),
    CONSTRAINT fk_air_log_station_station FOREIGN KEY (station) REFERENCES station (call)
);

CREATE INDEX ix_air_log_day ON air_log (day);

CREATE TABLE air_spot (
    id           INTEGER GENERATED BY DEFAULT AS IDENTITY,
    log_id       INTEGER     NOT NULL,
    hour         INTEGER     NOT NULL,
    break_number INTEGER     NOT NULL,
    position     INTEGER     NOT NULL,
    at           INTEGER     NOT NULL,
    order_number VARCHAR(24) NOT NULL,
    line         INTEGER     NOT NULL,
    advertiser   VARCHAR(16) NOT NULL,
    length       INTEGER     NOT NULL,
    grade        VARCHAR(32) NOT NULL,
    cart         VARCHAR(16) NOT NULL,
    fixed        BOOLEAN     NOT NULL,
    CONSTRAINT pk_air_spot PRIMARY KEY (id),
    CONSTRAINT uq_air_spot_log_id_hour_break_number_position UNIQUE (log_id, hour, break_number, position),
    CONSTRAINT fk_air_spot_log_id_air_log FOREIGN KEY (log_id) REFERENCES air_log (id) ON DELETE CASCADE,
    CONSTRAINT fk_air_spot_advertiser_advertiser FOREIGN KEY (advertiser) REFERENCES advertiser (code)
);

CREATE TABLE bump (
    id           INTEGER GENERATED BY DEFAULT AS IDENTITY,
    station      VARCHAR(16) NOT NULL,
    day          DATE        NOT NULL,
    hour         INTEGER     NOT NULL,
    break_number INTEGER     NOT NULL,
    order_number VARCHAR(24) NOT NULL,
    line         INTEGER     NOT NULL,
    advertiser   VARCHAR(16) NOT NULL,
    length       INTEGER     NOT NULL,
    grade        VARCHAR(32) NOT NULL,
    by_order     VARCHAR(24) NOT NULL,
    by_line      INTEGER     NOT NULL,
    made_good    BOOLEAN     NOT NULL,
    CONSTRAINT pk_bump PRIMARY KEY (id),
    CONSTRAINT fk_bump_station_station FOREIGN KEY (station) REFERENCES station (call),
    CONSTRAINT fk_bump_advertiser_advertiser FOREIGN KEY (advertiser) REFERENCES advertiser (code)
);

CREATE INDEX ix_bump_day ON bump (day);
CREATE INDEX ix_bump_order_number ON bump (order_number);

CREATE TABLE counter (
    series VARCHAR(16) NOT NULL,
    year   INTEGER     NOT NULL,
    last   INTEGER     NOT NULL,
    CONSTRAINT pk_counter PRIMARY KEY (series, year)
);
