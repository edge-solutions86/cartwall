-- The invoice, its detail and its summary.
--
-- Three tables and no clever normalisation. An invoice is a statement of what we
-- said we were owed on a date, so the money is stored rather than derived and the
-- detail is copied rather than joined. Everything an invoice was built from can be
-- revised afterwards and the invoice itself cannot.

CREATE TABLE invoice (
    number          VARCHAR(24)   NOT NULL,
    order_number    VARCHAR(24)   NOT NULL,
    advertiser      VARCHAR(16)   NOT NULL,
    payer           VARCHAR(16)   NOT NULL,
    year            INTEGER       NOT NULL,
    month           INTEGER       NOT NULL,
    raised          DATE          NOT NULL,
    spots           INTEGER       NOT NULL,
    gross           INTEGER       NOT NULL,
    commission_rate NUMERIC(5, 4) NOT NULL,
    commission      INTEGER       NOT NULL,
    net             INTEGER       NOT NULL,
    sent            BOOLEAN       NOT NULL,
    CONSTRAINT pk_invoice PRIMARY KEY (number),
    CONSTRAINT uq_invoice_order_number_year_month UNIQUE (order_number, year, month),
    CONSTRAINT fk_invoice_order_number_sales_order FOREIGN KEY (order_number) REFERENCES sales_order (number),
    CONSTRAINT fk_invoice_advertiser_advertiser FOREIGN KEY (advertiser) REFERENCES advertiser (code)
);

CREATE INDEX ix_invoice_raised ON invoice (raised);

CREATE TABLE invoice_detail (
    id             INTEGER GENERATED BY DEFAULT AS IDENTITY,
    invoice_number VARCHAR(24) NOT NULL,
    day            DATE        NOT NULL,
    at             INTEGER     NOT NULL,
    line           INTEGER     NOT NULL,
    length         INTEGER     NOT NULL,
    rate           INTEGER     NOT NULL,
    cart           VARCHAR(16) NOT NULL,
    moved          BOOLEAN     NOT NULL,
    CONSTRAINT pk_invoice_detail PRIMARY KEY (id),
    CONSTRAINT fk_invoice_detail_invoice_number_invoice
        FOREIGN KEY (invoice_number) REFERENCES invoice (number) ON DELETE CASCADE
);

CREATE TABLE invoice_summary (
    id             INTEGER GENERATED BY DEFAULT AS IDENTITY,
    invoice_number VARCHAR(24) NOT NULL,
    line           INTEGER     NOT NULL,
    station        VARCHAR(16) NOT NULL,
    daypart        VARCHAR(16) NOT NULL,
    length         INTEGER     NOT NULL,
    rate           INTEGER     NOT NULL,
    spots          INTEGER     NOT NULL,
    gross          INTEGER     NOT NULL,
    CONSTRAINT pk_invoice_summary PRIMARY KEY (id),
    CONSTRAINT uq_invoice_summary_invoice_number_line UNIQUE (invoice_number, line),
    CONSTRAINT fk_invoice_summary_invoice_number_invoice
        FOREIGN KEY (invoice_number) REFERENCES invoice (number) ON DELETE CASCADE
);
