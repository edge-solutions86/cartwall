-- The makegood ledger.
--
-- Two tables rather than one. A debt is raised the night the as-run says a spot did
-- not run and stays raised until something makes it good. An offer is a conversation
-- that can be refused, expire, and be followed by another offer against the same debt.
--
-- The unique key on a debt carries the cause. The same spot really can be owed twice
-- on one day, once because it errored and once because a political order bumped a
-- different airing, and those are two spots to give back.

CREATE TABLE makegood_debt (
    id           INTEGER GENERATED BY DEFAULT AS IDENTITY,
    order_number VARCHAR(24) NOT NULL,
    line         INTEGER     NOT NULL,
    advertiser   VARCHAR(16) NOT NULL,
    station      VARCHAR(16) NOT NULL,
    daypart      VARCHAR(16) NOT NULL,
    grade        VARCHAR(32) NOT NULL,
    length       INTEGER     NOT NULL,
    rate         INTEGER     NOT NULL,
    day          DATE        NOT NULL,
    cause        VARCHAR(32) NOT NULL,
    CONSTRAINT pk_makegood_debt PRIMARY KEY (id),
    CONSTRAINT uq_makegood_debt_line_day_cause UNIQUE (order_number, line, day, cause),
    CONSTRAINT fk_makegood_debt_order_number_sales_order FOREIGN KEY (order_number) REFERENCES sales_order (number)
);

CREATE INDEX ix_makegood_debt_order_number ON makegood_debt (order_number);
CREATE INDEX ix_makegood_debt_station ON makegood_debt (station);
CREATE INDEX ix_makegood_debt_day ON makegood_debt (day);

CREATE TABLE makegood_offer (
    id      INTEGER GENERATED BY DEFAULT AS IDENTITY,
    debt_id INTEGER     NOT NULL,
    day     DATE        NOT NULL,
    daypart VARCHAR(16) NOT NULL,
    rate    INTEGER     NOT NULL,
    state   VARCHAR(32) NOT NULL,
    short   BOOLEAN     NOT NULL,
    CONSTRAINT pk_makegood_offer PRIMARY KEY (id),
    CONSTRAINT fk_makegood_offer_debt_id_makegood_debt FOREIGN KEY (debt_id) REFERENCES makegood_debt (id)
);

CREATE INDEX ix_makegood_offer_debt_id ON makegood_offer (debt_id);
CREATE INDEX ix_makegood_offer_day ON makegood_offer (day);
